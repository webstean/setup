        run: |
          gh release create "$VERSION" \
            --title "$VERSION" \
            --generate-notes \
            --target "${{ github.ref_name }}" \
            ${{ inputs.prerelease && '--prerelease' || '--latest' }} \
            ${{ inputs.draft && '--draft' || '' }}
