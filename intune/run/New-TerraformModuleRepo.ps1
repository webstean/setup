            version="v0.1.0"
          elif [[ "$latest_tag" =~ ^v([0-9]+)\.([0-9]+)\.([0-9]+)$ ]]; then
            version="v${BASH_REMATCH[1]}.$((BASH_REMATCH[2] + 1)).0"
